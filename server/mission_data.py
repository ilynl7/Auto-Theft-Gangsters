def first_main_mission() -> str:
    """The first main-chain mission every new account gets (tutorial car
    kill / 杀怪 1001)."""
    return FIRST_MISSION


def next_main_mission(mission_id: str):
    """NextID of a main mission, or None at the end of the chain."""
    mdef = MAIN_MISSIONS.get(str(mission_id))
    return mdef["next"] if mdef else None


def is_main_mission(mission_id: str) -> bool:
    return str(mission_id) in MAIN_MISSIONS


def mission_reward(mission_id: str) -> dict:
    """Reward payout for completing a main mission (level-scaled)."""
    mdef = MAIN_MISSIONS.get(str(mission_id))
    lv = int(mdef["min_lv"]) if mdef else 1
    return {
        "gold": 200 + 300 * lv,
        "diamond": 1 + lv // 5,
        "exp": 200 + 250 * lv,
    }
