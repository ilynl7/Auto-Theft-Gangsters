				TutorialUIRootLogic.ShowWindow(component.gameObject, list, 70, 70, StrDictionary.GetClientDictionaryString("#{600075}"), SCREEN_DIRECTION.TOP_LEFT, isTipCircleEnable: true, isMaskEnable: true);
			}
			else
			{
				CloseTutorial();
			}
		}
		else
		{
			CloseTutorial();
		}
	}

	public static void MoveNext(bool needDelayFlag = false)
	{
		if (!needDelayFlag)
		{
			TutorialUIRootLogic.CloseWindow();
			ShowTutorial(mTutorialStepDic[mCurStep]);
			return;
		}
		vp_Timer.In(Time.deltaTime * 2f, delegate
		{
			TutorialUIRootLogic.CloseWindow();
			ShowTutorial(mTutorialStepDic[mCurStep]);
		});
	}

	public static void CloseTutorial()
	{
		if (mTutorialTweener != null)
		{
			mTutorialTweener.Kill();
		}
		TutorialUIRootLogic.CloseWindow();
		if (CurStep == TUTORIAL_STEP.MOVE_SCREEN)
		{
			MoveNext();
		}
		else
		{
			ShowTutorial(TUTORIAL_STEP.INVALID);
		}
	}

	public static bool IsTutorialCanShow()
	{
		if ((SingletonDontDestoryUnity<GameManager>.Instance.SceneManager != null && !SingletonDontDestoryUnity<GameManager>.Instance.SceneManager.IsBigWorld() && !SingletonDontDestoryUnity<GameManager>.Instance.SceneManager.IsTutorialScene()) || SingletonUnity<UIManager>.Instance.IsHideBaseUI || (SingletonUnity<MissionPassShowRootLogic>.Exists && UnityVersionUtil.IsActive(SingletonUnity<MissionPassShowRootLogic>.Instance.gameObject)) || (SingletonUnity<LevelUpUIRoot>.Exists && UnityVersionUtil.IsActive(SingletonUnity<LevelUpUIRoot>.Instance.gameObject)) || (SingletonUnity<LevelRewardGetLogic>.Exists && UnityVersionUtil.IsActive(SingletonUnity<LevelRewardGetLogic>.Instance.gameObject)) || (SingletonUnity<TutorialUIRootLogic>.Exists && UnityVersionUtil.IsActive(SingletonUnity<TutorialUIRootLogic>.Instance.gameObject)) || (SingletonUnity<TipCarUIRootLogic>.Exists && UnityVersionUtil.IsActive(SingletonUnity<TipCarUIRootLogic>.Instance.gameObject)) || SingletonDontDestoryUnity<GameManager>.Instance.SceneManager.LoadingFlag || (SingletonUnity<RebirthUIRootLogic>.Exists && UnityVersionUtil.IsActive(SingletonUnity<RebirthUIRootLogic>.Instance.gameObject)) || (SingletonUnity<OtherPlayerInfoUILogic>.Exists && UnityVersionUtil.IsActive(SingletonUnity<OtherPlayerInfoUILogic>.Instance.gameObject)))
